export const getCategoryById = (categoryId: CategoryId): Category | undefined => {
  return (
    PHASE1_CATEGORIES.find((c) => c.id === categoryId) ||
    CATEGORIES.find((c) => c.id === categoryId) ||
    MARKETPLACE_CATEGORIES.find((c) => c.id === categoryId)
  );
};

export const getCategorySubcategories = (categoryId: CategoryId): string[] => {
  const cat =
    PHASE1_CATEGORIES.find((c) => c.id === categoryId) ||
    MARKETPLACE_CATEGORIES.find((c) => c.id === categoryId);
  return cat?.subcategories || [];
};
